// Das Kartennetz spricht immer gegen die zweite Sprache des Paares, nie gegen die Basis selbst.
const ziel={de:'es',es:'de','pt-BR':'de'};
function bewertung({basis,wort,kandidat}){
  const record=matchWords(wort,directedContent(basis,ziel[basis]).vocabulary)[0];
  assert.ok(record.entry,basis+' '+wort);
  return assessIntendedMeaning(kandidat,record,basis);
}
test('every released everyday synonym counts as basic knowledge and keeps the noted word',()=>{
  assert.equal(freigegeben.length+abgelehnt.length,392);
  for(const zeile of freigegeben){
    const ergebnis=bewertung(zeile);
    assert.equal(ergebnis.status,'accepted',zeile.basis+' '+zeile.wort+' <= '+zeile.antwort+' -> '+zeile.kandidat);
    assert.ok(ergebnis.matches.some(m=>m.accepted.length),zeile.kandidat);
  }
});
test('what is not the same word stays unrecognized, including look-alikes and near words',()=>{
  for(const zeile of abgelehnt)
    assert.equal(bewertung(zeile).status,'unrecognized',zeile.basis+' '+zeile.wort+' <= '+zeile.antwort+' -> '+zeile.kandidat);
});
test('a released synonym sends the learner back to the noted word instead of nodding at the synonym',()=>{
  const ergebnis=bewertung({basis:'de',wort:'amigo',kandidat:'Kumpel'});
  assert.equal(ergebnis.status,'accepted');
  assert.ok(ergebnis.feedback.some(f=>f.level==='partial'));
  assert.ok(ergebnis.feedback.every(f=>f.canonical!=='kumpel'));
});
test('opposite wording never shares one concept group',()=>{
  const gas=relatedConcepts.de.filter(group=>group.includes('mit Kohlensäure')||group.includes('ohne Kohlensäure'));
  assert.equal(gas.length,2);
  assert.equal(gas.some(group=>group.includes('mit Kohlensäure')&&group.includes('ohne Kohlensäure')),false);
  assert.ok(!relatedConcepts.de.find(group=>group.includes('kalt')).includes('warm'));
});
test('a concept group has at least two members and never repeats one member',()=>{
  for(const [locale,groups]of Object.entries(relatedConcepts)){
    for(const group of groups){
      assert.ok(group.length>=2,locale+' '+group.join('/'));
      assert.equal(new Set(group.map(value=>value.toLocaleLowerCase('de'))).size,group.length,group.join('/'));
    }
  }
});
