import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {createStaticServer,loadAssets} from '../server/static-server.mjs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE_URL??'playwright');
const port=4186,origin=`http://127.0.0.1:${port}`;
const server=createStaticServer({assets:await loadAssets(),port});
let browser;
try {
  await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(port,'127.0.0.1',resolve);});
  browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE}:{})});
  const context=await browser.newContext({viewport:{width:390,height:844},permissions:['clipboard-read','clipboard-write']});
  await context.route('**/*',route=>new URL(route.request().url()).origin===origin?route.continue():route.abort());
  const page=await context.newPage(),errors=[];page.setDefaultTimeout(10000);page.on('pageerror',e=>errors.push(String(e)));
  await page.goto(origin);
  await page.getByRole('button',{name:'Meinen Einstieg finden',exact:true}).click();
  await page.getByRole('button',{name:/Ich kenne schon ein paar Worte/}).click();
  await page.getByLabel('Deine Wörter in Spanisch').fill('hola, agua, perro');
  await page.getByRole('button',{name:'Worte abgleichen',exact:true}).click();
  await page.getByRole('button',{name:'Mit diesen Worten weiter',exact:true}).click();
  const inputs=page.locator('.meaning-input');
  await inputs.nth(1).fill('Wasser, Gewässer');
  await page.evaluate(()=>navigator.clipboard.writeText('hallo, hi\r\nHund'));
  await inputs.nth(0).focus();await inputs.nth(0).press('Control+V');
  await page.waitForFunction(()=>document.querySelectorAll('.meaning-input')[2].value==='Hund');
  assert.deepEqual(await inputs.evaluateAll(fields=>fields.map(field=>field.value)),['hallo, hi','Wasser, Gewässer','Hund']);
  assert.match(await page.locator('[data-paste-status]').innerText(),/2 von 3/);
  await page.evaluate(()=>navigator.clipboard.writeText('hola: anders; perro: Wolf'));
  await inputs.nth(0).press('Control+V');
  await page.waitForFunction(()=>document.querySelector('[data-paste-status]').textContent.includes('nicht übernommen'));
  assert.deepEqual(await inputs.evaluateAll(fields=>fields.map(field=>field.value)),['hallo, hi','Wasser, Gewässer','Hund']);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await mkdir(new URL('../outputs/',import.meta.url),{recursive:true});
  await page.screenshot({path:fileURLToPath(new URL('../outputs/paste-browser.png',import.meta.url)),fullPage:true});
  await page.getByRole('button',{name:'Bedeutungen prüfen',exact:true}).click();
  const known=await page.evaluate(()=>JSON.parse(localStorage.getItem('sprachinseln.v1')).known);
  assert.equal(known.length,3);assert.deepEqual(errors,[]);
  console.log(JSON.stringify({paste:'clipboard event checked',drafts:'preserved',savedMeanings:known.length,errors}));
}finally{await browser?.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}
