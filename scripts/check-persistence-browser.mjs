import assert from 'node:assert/strict';
import {mkdir,mkdtemp} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {createStaticServer,loadAssets} from '../server/static-server.mjs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE_URL??'playwright');
const port=4187,origin=`http://127.0.0.1:${port}`,server=createStaticServer({assets:await loadAssets(),port});
let browser;
try{
 await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(port,'127.0.0.1',resolve);});
 await mkdir(new URL('../outputs/',import.meta.url),{recursive:true});
 const profileDir=await mkdtemp(fileURLToPath(new URL('../outputs/reload-profile-',import.meta.url)));
 const options={headless:true,viewport:{width:390,height:844},...(process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE}:{})};
 const context=await chromium.launchPersistentContext(profileDir,options);browser=context.browser();
 await context.route('**/*',route=>new URL(route.request().url()).origin===origin?route.continue():route.abort());
 let page=await context.newPage();page.setDefaultTimeout(10000);const errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto(origin);await page.getByRole('button',{name:'Meinen Einstieg finden',exact:true}).click();
 await page.getByRole('button',{name:/Ich kenne schon ein paar Worte/}).click();
 await page.getByLabel('Deine Wörter in Spanisch').fill('hola, agua, perro');
 await page.reload();assert.equal(await page.getByLabel('Deine Wörter in Spanisch').inputValue(),'hola, agua, perro');
 await page.getByRole('button',{name:'Worte abgleichen',exact:true}).click();
 await page.reload();await page.getByRole('button',{name:'Mit diesen Worten weiter',exact:true}).click();
 await page.locator('.meaning-input').nth(0).fill('hallo');await page.locator('.meaning-input').nth(1).fill('Wasser');
 await page.reload();assert.deepEqual(await page.locator('.meaning-input').evaluateAll(fields=>fields.map(input=>input.value)),['hallo','Wasser','']);
 await page.locator('.meaning-input').nth(2).fill('Hund');await page.getByRole('button',{name:'Bedeutungen prüfen',exact:true}).click();
 await page.getByRole('button',{name:/Alltagsgrundlagen/}).click();
 await page.getByRole('button',{name:'Lernrunde starten',exact:true}).click();
 await page.getByLabel('Deine Antwort in Spanisch',{exact:true}).fill('hola');await page.reload();
 assert.equal(await page.getByLabel('Deine Antwort in Spanisch',{exact:true}).inputValue(),'hola');
 await page.getByRole('button',{name:'Antwort prüfen',exact:true}).click();
 const attemptCount=()=>page.evaluate(()=>Object.values(JSON.parse(localStorage.getItem('sprachinseln.v1')).progress).reduce((sum,item)=>sum+item.attempts,0));
 assert.equal(await attemptCount(),1);await page.reload();assert.equal(await attemptCount(),1);
 await page.getByRole('button',{name:'Nächste Übung',exact:true}).click();
 const question=await page.locator('.question').innerText();
 await page.getByLabel('Deine Antwort in Spanisch',{exact:true}).fill('mein noch offener Versuch');
 await context.close();const reopened=await chromium.launchPersistentContext(profileDir,options);browser=reopened.browser();
 await reopened.route('**/*',route=>new URL(route.request().url()).origin===origin?route.continue():route.abort());
 page=await reopened.newPage();page.setDefaultTimeout(10000);page.on('pageerror',e=>errors.push(String(e)));await page.goto(origin);
 assert.equal(await page.locator('.question').innerText(),question);
 assert.equal(await page.getByLabel('Deine Antwort in Spanisch',{exact:true}).inputValue(),'mein noch offener Versuch');
 assert.equal(await attemptCount(),1);
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('sprachinseln.v1')).known.length),3);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await mkdir(new URL('../outputs/',import.meta.url),{recursive:true});
 await page.screenshot({path:fileURLToPath(new URL('../outputs/progress-resumed.png',import.meta.url)),fullPage:true});
 // Explicit reset affects only this isolated test profile.
 page.once('dialog',dialog=>dialog.dismiss());await page.getByRole('button',{name:'Debug: Profil komplett zurücksetzen',exact:true}).click();
 assert.equal(await attemptCount(),1);
 page.once('dialog',dialog=>dialog.accept());await page.getByRole('button',{name:'Debug: Profil komplett zurücksetzen',exact:true}).click();
 assert.equal(await page.evaluate(()=>localStorage.getItem('sprachinseln.v1')),null);
 await page.reload();await page.getByRole('button',{name:'Meinen Einstieg finden',exact:true}).waitFor();
 assert.deepEqual(errors,[]);console.log(JSON.stringify({reload:'all stages retained',browserReopen:'retained',attempts:'not duplicated',reset:'explicit only',errors}));
}finally{await browser?.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}
